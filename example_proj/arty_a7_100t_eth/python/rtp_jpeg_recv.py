# rtp_jpeg_recv.py - receive one RTP/JPEG (RFC 2435) frame over UDP and save it.
#
# A standalone alternative to ffplay/VLC for verifying the FPGA egress: binds the
# RTP UDP port, reassembles fragments (by RTP/JPEG fragment offset) until the RTP
# marker bit, rebuilds a baseline JFIF using the in-band quantization tables and
# the standard Annex-K Huffman tables, and writes out.jpg.
#
# Usage: python rtp_jpeg_recv.py [bind_port] [out.jpg]   (defaults 5004 out.jpg)

import socket
import struct
import sys

