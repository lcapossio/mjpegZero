def dht_segment():
    out = bytearray()
    for cls_id, bits, vals in [(0x00, DC_L_BITS, DC_L_VALS), (0x10, AC_L_BITS, AC_L_VALS),
                               (0x01, DC_C_BITS, DC_C_VALS), (0x11, AC_C_BITS, AC_C_VALS)]:
        body = bytes([cls_id]) + bits + vals
        out += b"\xff\xc4" + struct.pack(">H", len(body) + 2) + body
    return bytes(out)


def build_jfif(width, height, lqt, cqt, scan):
    j = bytearray(b"\xff\xd8")                                    # SOI
    j += b"\xff\xe0\x00\x10JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"  # APP0
    j += b"\xff\xdb\x00\x43\x00" + lqt                            # DQT luma
    j += b"\xff\xdb\x00\x43\x01" + cqt                            # DQT chroma
    # SOF0: 8-bit, 3 components, Y=2x1 (4:2:2) qt0, Cb/Cr 1x1 qt1
    j += b"\xff\xc0\x00\x11\x08" + struct.pack(">HH", height, width)
    j += bytes([0x03, 0x01, 0x21, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01])
    j += dht_segment()
    j += bytes([0xff, 0xda, 0x00, 0x0c, 0x03, 0x01, 0x00, 0x02, 0x11, 0x03, 0x11, 0x00, 0x3f, 0x00])
    j += scan
    j += b"\xff\xd9"                                              # EOI
    return bytes(j)


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 5004
    out  = sys.argv[2] if len(sys.argv) > 2 else "out.jpg"

    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.bind(("0.0.0.0", port))
    print("listening for RTP/JPEG on udp/%d ..." % port)

    frags = {}
    lqt = cqt = None
    width = height = 0

    while True:
        pkt, _ = s.recvfrom(2048)
        if len(pkt) < 20:
            continue
        marker = (pkt[1] >> 7) & 1
        pt = pkt[1] & 0x7f
        if pt != 26:
            continue
        o = 12                                   # past RTP header
        frag = (pkt[o + 1] << 16) | (pkt[o + 2] << 8) | pkt[o + 3]
        width = pkt[o + 6] * 8
        height = pkt[o + 7] * 8
        q = pkt[o + 5]
        o += 8
        if frag == 0 and q >= 128:
            o += 4                                # quant-table header
            lqt = pkt[o:o + 64]
            cqt = pkt[o + 64:o + 128]
            o += 128
        frags[frag] = pkt[o:]
        if marker:
            scan = bytearray()
            for off in sorted(frags):
                scan += frags[off]
            if lqt is None:
                print("  (no in-band tables seen; dropping frame)")
            else:
                jpg = build_jfif(width, height, lqt, cqt, bytes(scan))
                with open(out, "wb") as f:
                    f.write(jpg)
                print("  wrote %s (%dx%d, %d bytes, scan %d)"
                      % (out, width, height, len(jpg), len(scan)))
            frags = {}
            lqt = cqt = None


if __name__ == "__main__":
    main()
